package ru.itmo.plugins.attendance.tracking;

public enum CallStatus {
    /** Подписка ещё ни разу не установилась. */
    CONNECTING,
    /** Подписка активна, события применяются. */
    TRACKING,
    /** Связь потеряна после начала отслеживания; события за перерыв могут быть потеряны. */
    RECONNECTING,
    /** Платформа сообщила о завершении звонка. */
    ENDED,
    /** Источник отказал в подписке без повторов. */
    FAILED
}
